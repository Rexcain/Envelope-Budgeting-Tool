export const STRINGS = { zh, en };
let lang = 'zh';
export const setLang = l => { lang = STRINGS[l] ? l : 'zh'; document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en'; };
export const getLang = () => lang;
export const tf = key => STRINGS[lang][key] || STRINGS.en[key];
export function t(key, params) {
  const path = key.split('.');
  let v = STRINGS[lang];
  for (const k of path) v = v?.[k];
  if (v === undefined) { v = STRINGS.en; for (const k of path) v = v?.[k]; }
  return typeof v === 'function' ? v(params || {}) : v ?? key;
}
